export const LANGS = [
  { key: 'zh', label: '中文', html: 'zh-Hant' },
  { key: 'ja', label: '日本語', html: 'ja' },
  { key: 'en', label: 'English', html: 'en' },
];

function guess() {
  try {
    const saved = localStorage.getItem('clatter.lang');
    if (S[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.languages || [navigator.language || 'en']).map((l) => l.toLowerCase());
  for (const l of nav) {
    if (l.startsWith('zh')) return 'zh';
    if (l.startsWith('ja')) return 'ja';
    if (l.startsWith('en')) return 'en';
  }
  return 'en';
}

export let lang = guess();

export function setLang(k) {
  if (!S[k]) return;
  lang = k;
  try {
    localStorage.setItem('clatter.lang', k);
  } catch (e) {}
  applyDom();
}

export function t(key, vars) {
  let s = S[lang][key] ?? S.zh[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

export function applyDom(root = document) {
  document.documentElement.lang = LANGS.find((l) => l.key === lang).html;
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}
